"""Writes MeeTuneHrtf.java: MeeTune Spatial sound's head model, from MIT KEMAR (compact set).

Usage: python tools/kemar_hrtf.py <unzipped compact.zip dir>
Data: https://sound.media.mit.edu/resources/KEMAR/compact.zip (Gardner & Martin, MIT Media Lab, 1994).

Two speakers at +-30 degrees, ear height, are symmetric, so the four ear filters fold into two on
mid/side: mid through S = ipsi + contra, side through D = ipsi - contra. Both are divided by S's
smoothed magnitude, so a centred voice keeps its tone and only the difference between the ears
(arrival time, head shadow) is added. Written for 44.1 and 48 kHz.
"""
import os
import sys
import wave

import numpy as np

TAPS = 160
LEAD = 16  # samples of delay so nothing rings before the impulse
N = 1024


def read(path):
    with wave.open(path) as w:
        pcm = np.frombuffer(w.readframes(w.getnframes()), dtype='<i2').astype(float) / 32768
    return pcm[0::2], pcm[1::2]  # left ear, right ear; the source is on the right


def smooth(mag, freqs):
    out = np.empty_like(mag)
    for i, f in enumerate(freqs):
        band = (freqs >= f / 2 ** (1 / 6)) & (freqs <= f * 2 ** (1 / 6)) if f > 0 else freqs == 0
        out[i] = np.sqrt(np.mean(mag[band] ** 2))
    return out


def filters(left, right, rate):
    contra, ipsi = left, right
    freqs = np.fft.rfftfreq(N, 1 / 44100)
    s = np.fft.rfft(ipsi + contra, N)
    d = np.fft.rfft(ipsi - contra, N)
    norm = np.maximum(smooth(np.abs(s), freqs), 1e-3)
    s, d = s / norm, d / norm
    out = []
    for h in (s, d):
        ir = np.fft.irfft(h, N)
        if rate != 44100:  # resample the impulse (KEMAR is 44.1 kHz)
            t = np.arange(N) * 44100 / rate
            ir = np.sinc(t[:, None] - np.arange(N)[None, :]) @ ir * 44100 / rate
        ir = np.roll(ir, LEAD)[:TAPS]
        ir[:LEAD // 2] *= np.hanning(LEAD)[:LEAD // 2]
        ir[-32:] *= np.hanning(64)[32:]
        out.append(ir)
    return out


def java_array(name, values):
    body = ', '.join('%.6ff' % v for v in values)
    return '    static final float[] %s = {%s};\n' % (name, body)


def main():
    left, right = read(os.path.join(sys.argv[1], 'elev0', 'H0e030a.wav'))
    src = ['package com.newtube.mobile.ui.meetune;\n\n',
           '/** Generated by tools/kemar_hrtf.py from MIT KEMAR (Gardner & Martin, MIT Media Lab, 1994).'
           ' Do not edit. */\n',
           'final class MeeTuneHrtf {\n',
           '    /** Samples of delay both filters share. */\n',
           '    static final int LEAD = %d;\n\n' % LEAD]
    for rate in (44100, 48000):
        mid, side = filters(left, right, rate)
        src.append(java_array('MID_%d' % rate, mid))
        src.append(java_array('SIDE_%d' % rate, side))
    src.append('\n    private MeeTuneHrtf() {\n    }\n}\n')
    out = 'mobile/src/stmobile/java/com/newtube/mobile/ui/meetune/MeeTuneHrtf.java'
    with open(out, 'w', newline='\n') as f:
        f.write(''.join(src))
    print('wrote', out)


if __name__ == '__main__':
    main()
